    @Test
    void scannerShouldAcceptProvidedFixedCallsAndRejectMissingWrappers(@TempDir Path tempDir) throws IOException {
        var helperRoot = tempDir.resolve("gdcc");
        var templateRoot = tempDir.resolve("templates");
        Files.createDirectories(helperRoot);
        Files.createDirectories(templateRoot);
        Files.writeString(helperRoot.resolve("ok.h"), """
                static inline godot_int godot_local_helper(void) {
                    return 0;
                }
                
                static inline void use_fixed(GDExtensionObjectPtr self) {
                    godot_Object_call(self, 0, 0, 0);
                    godot_local_helper();
                }
                """);

        assertTrue(GdccHelperBindingScanner.scan(
                helperRoot,
                templateRoot,
                Set.of("godot_Object_call")
        ).isEmpty());

        Files.writeString(templateRoot.resolve("missing.ftl"), """
                ${"godot_Missing_fixed"}();
                """);

        var failure = assertThrows(
                IllegalStateException.class,
                () -> GdccHelperBindingScanner.checkFixedCoverage(
                        helperRoot,
                        templateRoot,
                        Set.of("godot_Object_call")
                )
        );

        assertTrue(failure.getMessage().contains("godot_Missing_fixed"));
    }

    @Test
    void checkFixedShouldUseInterfaceProvidedSetAndRejectInterfaceTypos(@TempDir Path tempDir) throws IOException {
        var includeRoot = tempDir.resolve("include");
        var helperRoot = includeRoot.resolve("gdcc");
        var templateRoot = tempDir.resolve("templates");
        var interfaceHeader = includeRoot.resolve("godot").resolve("gdextension").resolve("gdextension_interface.h");
        Files.createDirectories(helperRoot);
        Files.createDirectories(templateRoot);
        Files.createDirectories(interfaceHeader.getParent());
        Files.writeString(interfaceHeader, """
                /**
                 * @name object_method_bind_call
                 */
                typedef void (*GDExtensionInterfaceObjectMethodBindCall)(
                        GDExtensionMethodBindPtr p_method_bind,
                        GDExtensionObjectPtr p_instance,
                        const GDExtensionConstVariantPtr *p_args,
                        GDExtensionInt p_arg_count,
                        GDExtensionUninitializedVariantPtr r_ret,
                        GDExtensionCallError *r_error);
                """);
        Files.writeString(helperRoot.resolve("ok.h"), """
                static inline void use_interface_wrapper(
                        GDExtensionMethodBindPtr bind,
                        GDExtensionObjectPtr object,
                        GDExtensionCallError *error
                ) {
                    godot_object_method_bind_call(bind, object, 0, 0, 0, error);
                }
                """);

        GodotBindingTool.run(new String[]{
                "check-fixed",
                "--gde",
                "4.5.1",
                "--helper-root",
                helperRoot.toString(),
                "--template-root",
                templateRoot.toString()
        });

        Files.writeString(templateRoot.resolve("typo.ftl"), """
                ${"godot_object_method_bind_calll"}();
                """);

        var failure = assertThrows(IllegalStateException.class, () -> GodotBindingTool.run(new String[]{
                "check-fixed",
                "--gde",
                "4.5.1",
                "--helper-root",
                helperRoot.toString(),
                "--template-root",
                templateRoot.toString()
        }));

        assertTrue(failure.getMessage().contains("godot_object_method_bind_calll"));
    }

