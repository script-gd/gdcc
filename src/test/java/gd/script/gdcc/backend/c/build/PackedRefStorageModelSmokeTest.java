    /// ptrcall boundary probe: mirrors the generated wrapper sequence in
    /// `entry.h.ftl` (`ptrcall<bind>`): inbound `variant_from_struct` materialization, callee on
    /// the internal pointer, outbound `struct_from_variant` copy, wrapper-owned cleanup.
    private static final String PTRCALL_PROBE = FAKE_ENGINE + """
            
            // Stands in for the generated user function `func mutate(p: PackedInt32Array)
            // -> PackedInt32Array: p.push_back(7); return p` — mutation through the internal
            // pointer, return through an identity-sharing holder copy.
            static godot_Variant fake_callee_mutate(godot_Variant *p) {
                probe_push(gdcc_packed_int32_array_internal_ptr(p), 7);
                // A callee-side alias must observe the mutation (shared identity inside).
                godot_Variant callee_alias = gdcc_packed_ref_copy(p);
                CHECK(probe_size(gdcc_packed_int32_array_internal_ptr(&callee_alias)) == 2,
                        "callee alias must observe the in-place mutation");
                gdcc_packed_ref_destroy(&callee_alias);
                return gdcc_packed_ref_copy(p);
            }
            
            int main(void) {
                godot_initialize_interface(&fake_get_proc_address);
                gdcc_packed_ref_init();
            
                // Caller side: a live array [1] whose identity must survive the boundary intact.
                godot_Variant caller = gdcc_packed_int32_array_new_empty();
                probe_push(gdcc_packed_int32_array_internal_ptr(&caller), 1);
                int64_t caller_id = probe_id_of_variant(&caller);
            
                // The engine hands the callee a RAW STRUCT slot across ptrcall (Vector-layer copy).
                godot_PackedInt32Array caller_slot = gdcc_packed_int32_array_struct_from_variant(&caller);
            
                // === generated ptrcall wrapper body (entry.h.ftl ptrcall<bind>) ===
                const GDExtensionConstTypePtr p_args[] = { &caller_slot };
                godot_PackedInt32Array ret_slot;
                {
                    godot_Variant arg0 = gdcc_packed_int32_array_variant_from_struct(
                            (const godot_PackedInt32Array *)p_args[0]);
                    godot_Variant r = fake_callee_mutate(&arg0);
                    *((godot_PackedInt32Array *)&ret_slot) = gdcc_packed_int32_array_struct_from_variant(&r);
                    godot_Variant_destroy(&r);
                    godot_Variant_destroy(&arg0);
                }
                // === end generated wrapper body ===
            
                int caller_unchanged = probe_size(&caller_slot) == 1 && probe_get(&caller_slot, 0) == 1;
                int ret_has_mutation = probe_size(&ret_slot) == 2 && probe_get(&ret_slot, 0) == 1 && probe_get(&ret_slot, 1) == 7;
                int distinct_identity = probe_id_of_struct(&caller_slot) != probe_id_of_struct(&ret_slot)
                        && probe_id_of_variant(&caller) != probe_id_of_struct(&ret_slot);
                CHECK(caller_unchanged, "ptrcall boundary must isolate the caller from callee mutation");
                CHECK(ret_has_mutation, "ptrcall return must carry the callee mutation out");
                CHECK(distinct_identity, "ptrcall boundary must not share identity in either direction");
                printf("PTRCALL_ISOLATION caller_unchanged=%d ret_has_mutation=%d distinct_identity=%d\\n",
                        caller_unchanged, ret_has_mutation, distinct_identity);
                printf("CALLEE_SHARED visible=1\\n");
            
                godot_PackedInt32Array_destroy(&ret_slot);
                godot_PackedInt32Array_destroy(&caller_slot);
                gdcc_packed_ref_destroy(&caller);
                CHECK(g_live == 0, "holder leak across ptrcall boundary");
                // new_empty's temporary struct + the two boundary slots, each destroyed exactly once.
                CHECK(g_struct_destroy_calls == 3, "raw struct slots must be destroyed exactly once");
                printf("BALANCED\\n");
                printf("PROBE_DONE\\n");
                return 0;
            }
            """;
