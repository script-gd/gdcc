        private void addMethodSymbols(@NotNull List<GodotBindingSymbol> symbols, @NotNull ExtensionBuiltinClass builtin) {
            var memberNames = memberNames(builtin);
            for (var method : GodotBindingSupport.list(builtin.methods())) {
                if (isMemberAccessorConflict(method, memberNames)) {
                    continue;
                }
                var parameters = new ArrayList<GodotBindingSymbol.Parameter>();
                parameters.add(new GodotBindingSymbol.Parameter(
                        "self",
                        (method.isConst() ? "const " : "") + GodotBindingSupport.cType(builtin.name()) + " *",
                        method.isConst() ? GodotBindingSymbol.Abi.CONST_TYPE_PTR : GodotBindingSymbol.Abi.MUTABLE_TYPE_PTR
                ));
                parameters.addAll(parameters(GodotBindingSupport.list(method.arguments())));
                symbols.add(GodotBindingSupport.symbol(
                        GodotBindingSymbol.Family.BUILTIN,
                        builtin.name(),
                        method.name(),
                        methodName(builtin.name(), method.name()),
                        GodotBindingSupport.returnCType(method.returnType()),
                        parameters,
                        method.isVararg(),
                        method.hash(),
                        GodotBindingSupport.list(method.hashCompatibility())
                ));
            }
        }

