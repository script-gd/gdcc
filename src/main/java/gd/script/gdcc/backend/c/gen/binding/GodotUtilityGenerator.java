package gd.script.gdcc.backend.c.gen.binding;

import gd.script.gdcc.gdextension.ExtensionAPI;
import gd.script.gdcc.gdextension.ExtensionUtilityFunction;
import org.jetbrains.annotations.NotNull;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

final class GodotUtilityGenerator {
    private GodotUtilityGenerator() {
    }

    static void generateUtilitySupport(@NotNull ExtensionAPI api, @NotNull Path out) throws IOException {
        Files.createDirectories(out);
        for (var entry : renderUtilitySupport(api).entrySet()) {
            Files.writeString(out.resolve(entry.getKey()), entry.getValue());
        }
    }

    static @NotNull Map<String, String> renderUtilitySupport(@NotNull ExtensionAPI api) {
        Objects.requireNonNull(api);
        GodotBindingSymbolHelper.validate(collectSymbols(api));
        var renderer = new UtilityRenderer(api);
        var files = new LinkedHashMap<String, String>();
        files.put("godot_utility.h", renderer.renderHeader());
        files.put("godot_utility.c", renderer.renderSource());
        return files;
    }

    static @NotNull List<GodotBindingSymbol> collectSymbols(@NotNull ExtensionAPI api) {
        var symbols = new ArrayList<GodotBindingSymbol>();
        for (var function : GodotBindingSupport.list(api.utilityFunctions())) {
            var parameters = new ArrayList<GodotBindingSymbol.Parameter>();
            for (var argument : GodotBindingSupport.list(function.arguments())) {
                parameters.add(new GodotBindingSymbol.Parameter(
                        GodotBindingSupport.parameterName(argument.name()),
                        GodotBindingSupport.publicParameterType(argument.type()),
                        GodotBindingSupport.isPointerPublicType(argument.type())
                                ? GodotBindingSymbol.Abi.CONST_TYPE_PTR
                                : GodotBindingSymbol.Abi.VALUE
                ));
            }
            if (function.isVararg()) {
                parameters.add(new GodotBindingSymbol.Parameter("argv", "const godot_Variant **",
                        GodotBindingSymbol.Abi.VARIANT_VARARG));
                parameters.add(new GodotBindingSymbol.Parameter("argc", "godot_int", GodotBindingSymbol.Abi.VALUE));
            }
            symbols.add(GodotBindingSupport.symbol(
                    GodotBindingSymbol.Family.UTILITY,
                    "Global",
                    function.name(),
                    utilityName(function.name()),
                    GodotBindingSupport.returnCType(function.returnType()),
                    parameters,
                    function.isVararg(),
                    Integer.toUnsignedLong(function.hash()),
                    List.of()
            ));
        }
        return GodotBindingSymbolHelper.validate(symbols);
    }

    private static @NotNull String utilityName(@NotNull String name) {
        return "godot_" + GodotBindingSupport.cIdentifier(name);
    }

    private static final class UtilityRenderer {
        private final @NotNull List<ExtensionUtilityFunction> functions;

        private UtilityRenderer(@NotNull ExtensionAPI api) {
            this.functions = GodotBindingSupport.list(api.utilityFunctions());
        }

        private @NotNull String renderHeader() {
            var out = new StringBuilder(GodotBindingSupport.headerPreamble("GDCC_GODOT_UTILITY_H"));
            out.append("""
                    
                    #include <godot_builtin.h>
                    
                    #ifdef __cplusplus
                    extern "C" {
                    #endif
                    
                    """);
            for (var function : functions) {
                out.append("GDCC_GODOT_DECL ")
                        .append(GodotBindingSupport.returnCType(function.returnType()))
                        .append(' ')
                        .append(utilityName(function.name()))
                        .append('(')
                        .append(renderParameters(function))
                        .append(");\n");
            }
            out.append("""
                    
                    #ifdef __cplusplus
                    }
                    #endif
                    
                    #endif
                    """);
            return out.toString();
        }

        private @NotNull String renderSource() {
            var out = new StringBuilder("""
                    /* This file was generated by GodotUtilityGenerator. */
                    /* Do not edit by hand. */
                    #include "godot_utility.h"
                    
                    """);
            out.append(GodotBindingSupport.sourceBindingMacros());
            for (var function : functions) {
                appendDefinition(out, function);
            }
            return out.toString();
        }

        private void appendDefinition(@NotNull StringBuilder out, @NotNull ExtensionUtilityFunction function) {
            var functionName = utilityName(function.name());
            var cacheName = "gdcc_utility_" + GodotBindingSupport.cIdentifier(function.name());
            out.append("static GDExtensionPtrUtilityFunction ").append(cacheName).append(" = NULL;\n\n");
            out.append(GodotBindingSupport.returnCType(function.returnType())).append(' ')
                    .append(functionName).append('(').append(renderParameters(function)).append(") {\n")
                    .append("    GDCC_RESOLVE_UTILITY_CACHE(")
                    .append(cacheName)
                    .append(", \"")
                    .append(GodotBindingSupport.escapeCString(function.name()))
                    .append("\", ")
                    .append(GodotBindingSupport.renderUnsignedInt(Integer.toUnsignedLong(function.hash())))
                    .append(", \"")
                    .append(GodotBindingSupport.escapeCString(functionName))
                    .append("\", ");
            if (GodotBindingSupport.isVoid(function.returnType())) {
                out.append("return");
            } else {
                out.append("return ").append(GodotBindingSupport.zeroReturn(function.returnType()));
            }
            out.append(");\n");
            appendUtilityArgs(out, function);
            if (!GodotBindingSupport.isVoid(function.returnType())) {
                out.append("    ")
                        .append(GodotBindingSupport.initializedCarrierDeclaration(
                                GodotBindingSupport.returnCType(function.returnType()),
                                "result"
                        ))
                        .append(";\n");
            }
            out.append("    ").append(cacheName).append('(')
                    .append(GodotBindingSupport.isVoid(function.returnType()) ? "NULL" : "(GDExtensionTypePtr)&result")
                    .append(", ")
                    .append(argumentCount(function) == 0 && !function.isVararg() ? "NULL" : "args")
                    .append(", ")
                    .append(function.isVararg()
                            ? "(int)(" + GodotBindingSupport.list(function.arguments()).size() + " + argc)"
                            : String.valueOf(GodotBindingSupport.list(function.arguments()).size()))
                    .append(");\n");
            if (!GodotBindingSupport.isVoid(function.returnType())) {
                out.append("    return result;\n");
            }
            out.append("}\n\n");
        }

        private static @NotNull String renderParameters(@NotNull ExtensionUtilityFunction function) {
            var params = new ArrayList<String>();
            for (var argument : GodotBindingSupport.list(function.arguments())) {
                params.add(GodotBindingSupport.renderPublicParameter(argument.type(), argument.name()));
            }
            if (function.isVararg()) {
                params.add("const godot_Variant **argv");
                params.add("godot_int argc");
            }
            return params.isEmpty() ? "void" : String.join(", ", params);
        }

        private static void appendUtilityArgs(@NotNull StringBuilder out, @NotNull ExtensionUtilityFunction function) {
            var fixedArguments = GodotBindingSupport.list(function.arguments());
            if (fixedArguments.isEmpty() && !function.isVararg()) {
                return;
            }
            if (function.isVararg()) {
                out.append("    GDExtensionConstTypePtr args[")
                        .append(fixedArguments.size())
                        .append(" + argc];\n");
                for (var i = 0; i < fixedArguments.size(); i++) {
                    var argument = fixedArguments.get(i);
                    out.append("    args[").append(i).append("] = ")
                            .append(GodotBindingSupport.typePtrArgument(
                                    argument.type(),
                                    GodotBindingSupport.parameterName(argument.name())
                            ))
                            .append(";\n");
                }
                out.append("    for (godot_int index = 0; index < argc; index++) {\n")
                        .append("        args[").append(fixedArguments.size()).append(" + index] = ")
                        .append("(GDExtensionConstTypePtr)argv[index];\n")
                        .append("    }\n");
                return;
            }
            out.append("    const GDExtensionConstTypePtr args[] = { ");
            var rendered = new ArrayList<String>();
            for (var argument : fixedArguments) {
                rendered.add(GodotBindingSupport.typePtrArgument(
                        argument.type(),
                        GodotBindingSupport.parameterName(argument.name())
                ));
            }
            out.append(String.join(", ", rendered)).append(" };\n");
        }

        private static int argumentCount(@NotNull ExtensionUtilityFunction function) {
            return GodotBindingSupport.list(function.arguments()).size();
        }
    }
}
