    static @NotNull String parameterName(@Nullable String rawName) {
        var name = rawName == null || rawName.isBlank() ? "arg" : cIdentifier(rawName);
        return C_KEYWORDS.contains(name) ? name + "_arg" : name;
    }

    public static @NotNull String cIdentifier(@NotNull String raw) {
        var identifier = raw.replaceAll("[^A-Za-z0-9_]", "_").replaceAll("_+", "_");
        if (identifier.isBlank()) {
            throw new IllegalArgumentException("Cannot render blank C identifier from '" + raw + "'");
        }
        if (Character.isDigit(identifier.charAt(0))) {
            identifier = "_" + identifier;
        }
        return identifier;
    }

    public static @NotNull String escapeCString(@NotNull String value) {
        return value.replace("\\", "\\\\").replace("\"", "\\\"");
    }

    static @NotNull String versionLabel(@NotNull ExtensionAPI api) {
        var header = api.header();
        if (header == null) {
            return "<missing>";
        }
        return header.versionMajor() + "." + header.versionMinor() + "." + header.versionPatch();
    }

    static @NotNull String renderUnsignedInt(long value) {
        return Long.toUnsignedString(value) + "LL";
    }
